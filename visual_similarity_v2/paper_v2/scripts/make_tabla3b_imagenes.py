"""BORRADOR. Tabla 3b (EXPLORATORIA): 12 imágenes superordinadas dentro del dominio x 8 encoders entrenados,
decisión del aprendiz centroide tras enseñanza amplia (3sup) y adultos k/600. Además, la tortuga en los tres contextos.
Lee one_word_items.csv fijado en el commit a945ed2 (git show) y coteja adultos con los datos por ensayo congelados.
Uso: python make_tabla3b_imagenes.py <checkout del repo en a945ed2>
"""
import io, subprocess, sys
from pathlib import Path
import pandas as pd

REPO = Path(sys.argv[1]); COMMIT = "a945ed2cbdd9365fe346b262763f0262eaf686ea"
OUT = Path(__file__).resolve().parents[1] / "generated"; OUT.mkdir(exist_ok=True)
def show(p): return subprocess.run(["git", "-C", str(REPO), "show", f"{COMMIT}:{p}"], capture_output=True, check=True).stdout
OWI = "visual_similarity_v2/agents_xtmem_v2/outputs/one_word_items.csv"
HL = "visual_similarity_v2/encoder_equivalence_v2/encoder_equivalence/data/h4_long_R0_dinov2s.csv"
d = pd.read_csv(io.BytesIO(show(OWI)))
T8 = ["R0_dinov2s","O1_dinov2b","R1_cvcl","E1_siglip","O2_openclip","E2_vitsup","E3_rn50sup","E4_mae"]
SHORT = {"R0_dinov2s":"DINOv2-s","O1_dinov2b":"DINOv2-b","R1_cvcl":"CVCL","E1_siglip":"SigLIP","O2_openclip":"OpenCLIP",
         "E2_vitsup":"ViT","E3_rn50sup":"RN50","E4_mae":"MAE"}
# Rótulos de las imágenes: inspección visual de XTMEM 220ed17e experiments/image_stim/images/ (hoja en
# verificacion/hoja_estimulos_sup.png); los marcados * coinciden además con PAIRS en agents_xtmem_v2/run.py.
LABEL = {"c1_sup1":"celery","c1_sup2":"potato","c1_sup3":"radish*","c1_sup4":"broccoli*",
         "c2_sup1":"dump truck","c2_sup2":"red railway car","c2_sup3":"blue car*","c2_sup4":"gray car*",
         "c3_sup1":"rabbit*","c3_sup2":"turtle*","c3_sup3":"horse","c3_sup4":"cat"}
DOM = {"vegetables":"c1","vehicles":"c2","animals":"c3"}
c = d[(d.learner=="centroid") & (d.condition=="3sup")]
w = c[(c.image.str[:2]==c.domain.map(DOM)) & c.image.str.contains("_sup")]
assert w.groupby(["domain","image"]).human_yes.nunique().max()==1
tab = w[w.encoder.isin(T8)].pivot_table(index=["domain","image"], columns="encoder", values="accepted").astype(int)[T8]
hum = w[w.encoder=="R0_dinov2s"].set_index(["domain","image"])[["human_yes","human_n"]]
tab = hum.join(tab).reset_index()
order = {"animals":0,"vegetables":1,"vehicles":2}
tab = tab.sort_values(["domain","image"], key=lambda s: s.map(order) if s.name=="domain" else s)
tab.insert(2, "label", tab.image.map(LABEL))
csv = tab.copy()
for e in T8: csv[e] = csv[e].map({1:"accept",0:"reject"})
csv.to_csv(OUT/"tab3b_imagenes_por_encoder.csv", index=False)

# chequeos
checks = []
hl = pd.read_csv(io.BytesIO(show(HL)))
hl = hl[hl.condition.isin(["3sup","three_superordinate"])]
for _, r in tab.iterrows():
    s = hl[(hl.category==r.domain) & (hl.image==r.image)]
    checks.append((f"adultos {r.domain} {r.image} = h4_long", s.selected.sum()==r.human_yes and len(s)==r.human_n, f"{s.selected.sum()}/{len(s)}"))
for e, k in [("E2_vitsup",10),("O1_dinov2b",10)]:
    checks.append((f"{e} acepta {k}/12", tab[e].sum()==k, str(tab[e].sum())))
dis = tab[tab.E2_vitsup != tab.O1_dinov2b]
checks.append(("ViT y DINOv2-b discrepan en 4 imágenes", len(dis)==4, ", ".join(dis.image)))
checks.append(("ViT y DINOv2-b coinciden (aceptan) en las otras 8", ((tab.E2_vitsup==tab.O1_dinov2b) & (tab.E2_vitsup==1)).sum()==8, ""))
e3 = tab.groupby("domain").E3_rn50sup.sum().to_dict()
checks.append(("E3 acepta 4 animales, 4 vegetales, 0 vehículos", e3=={"animals":4,"vegetables":4,"vehicles":0}, str(e3)))
veh = tab[tab.domain=="vehicles"]
checks.append(("vagón = vehículo menos elegido por adultos", veh.loc[veh.human_yes.idxmin(),"image"]=="c2_sup2", str(veh.human_yes.min())))
# tortuga en los tres contextos
t = c[(c.image=="c3_sup2") & c.encoder.isin(T8)].pivot_table(index="domain", columns="encoder", values="accepted").astype(int)[T8]
th = c[(c.image=="c3_sup2") & (c.encoder=="R0_dinov2s")].set_index("domain")[["human_yes","human_n"]]
tt = th.join(t).loc[["animals","vehicles","vegetables"]].reset_index()
tt.to_csv(OUT/"tab3c_tortuga_por_contexto.csv", index=False)
checks.append(("tortuga: adultos 431/600 (animales) y 1/600 (vehículos)",
               (tt.set_index("domain").loc["animals","human_yes"], tt.set_index("domain").loc["vehicles","human_yes"])==(431,1), ""))
checks.append(("tortuga: DINOv2-b acepta en animales y vehículos; ViT rechaza en ambos",
               list(tt.set_index("domain").loc[["animals","vehicles"],"O1_dinov2b"])==[1,1] and list(tt.set_index("domain").loc[["animals","vehicles"],"E2_vitsup"])==[0,0], ""))
for dom in ["animals","vehicles"]:
    s = hl[(hl.category==dom) & (hl.image=="c3_sup2")]
    checks.append((f"tortuga {dom} = h4_long", s.selected.sum()==tt.set_index("domain").loc[dom,"human_yes"], f"{s.selected.sum()}/{len(s)}"))

# .tex
AR = {1:"A", 0:"R"}
L = [r"% AUTO-GENERATED by scripts/make_tabla3b_imagenes.py from one_word_items.csv @ a945ed2 -- do not edit (requires graphicx, booktabs)",
     r"\setlength{\tabcolsep}{4pt}", r"\noindent\resizebox{\linewidth}{!}{%", r"\begin{tabular}{lllc" + "c"*len(T8) + "}", r"\toprule",
     r"Taught domain & Image ID & Visual description & Adults ($k$/600) & " + " & ".join(SHORT[e] for e in T8) + r" \\",
     r"\midrule"]  # leyenda A/R va en el caption
prev = None
for _, r in tab.iterrows():
    if prev is not None and r.domain != prev: L.append(r"\midrule")
    L.append(" & ".join([r.domain.capitalize() if r.domain != prev else "", r"\texttt{" + r.image.replace("_", r"\_") + "}", r.label.replace("*", ""),
                         f"{r.human_yes}"] + [AR[r[e]] for e in T8]) + r" \\")
    prev = r.domain
L.append(r"\midrule")
L.append(" & ".join(["Accepted", "", "", f"{tab.human_yes.sum()}/{tab.human_n.sum()}"] + [f"{tab[e].sum()}/12" for e in T8]) + r" \\")
L += [r"\bottomrule", r"\end{tabular}}"]
(OUT/"tab3b_imagenes_por_encoder.tex").write_text("\n".join(L) + "\n")
L2 = [r"% AUTO-GENERATED by scripts/make_tabla3b_imagenes.py -- do not edit (requires graphicx, booktabs)",
      r"\setlength{\tabcolsep}{4pt}", r"\noindent{%", r"\begin{tabular}{lc" + "c"*len(T8) + "}", r"\toprule",
      r"Context & Adults ($k$/600) & " + " & ".join(SHORT[e] for e in T8) + r" \\", r"\midrule"]
for _, r in tt.iterrows():
    L2.append(" & ".join([r.domain.capitalize(), str(r.human_yes)] + [AR[r[e]] for e in T8]) + r" \\")
L2 += [r"\bottomrule", r"\end{tabular}}"]
(OUT/"tab3c_tortuga_por_contexto.tex").write_text("\n".join(L2) + "\n")
with open(OUT/"chequeos_tabla3b.txt", "w") as f:
    f.write(f"fuente: {OWI} @ {COMMIT}\n")
    for n, ok, det in checks: f.write(f"{'OK ' if ok else 'FALLA'} {n} {det}\n")
print(len(checks), "chequeos,", sum(not ok for _, ok, _ in checks), "fallas")
