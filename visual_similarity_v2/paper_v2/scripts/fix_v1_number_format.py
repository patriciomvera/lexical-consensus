"""Typographic-only rewrite of the v1 macro file (values unchanged) for the v2b manuscript:
- a leading "$-$" closes math mode when the macro is used inside $...$ (rendered as "=-" with a text hyphen);
  it becomes \\ensuremath{-}, which works in text and in math;
- a thousands comma between digits (e.g. 3,695.4) gets extra space in math mode ("3, 695.4"); it becomes {,}.
Usage: python fix_v1_number_format.py IN.tex OUT.tex  (asserts that the numeric content is identical)."""
import re, sys
src = open(sys.argv[1]).read()
out = src.replace("$-$", r"\ensuremath{-}")
out = re.sub(r"(?<=\d),(?=\d{3}(\D|$))", "{,}", out)
norm = lambda s: re.sub(r"\\ensuremath\{-\}|\$-\$", "-", s).replace("{,}", ",")
assert norm(out) == norm(src)
# 2-decimal versions of the primary H4 interval, for Table 1 (whose other rows use 2 decimals); rounded from the same macros
from decimal import Decimal, ROUND_HALF_UP
for k in ("HFourLo", "HFourHi"):
    v = re.search(r"\\newcommand\{\\" + k + r"\}\{(.*?)\}\n", out).group(1)
    x = Decimal(v.replace(r"\ensuremath{-}", "-")).quantize(Decimal("0.01"), ROUND_HALF_UP)
    out += "\\newcommand{\\" + k + "short}{" + str(x).replace("-", r"\ensuremath{-}") + "}\n"
open(sys.argv[2], "w").write("% AUTO-GENERATED by scripts/fix_v1_number_format.py from numbers.tex (typography only) -- do not edit\n" + out)
print("v1 macros reformatted:", sum(1 for a, b in zip(src.splitlines(), out.splitlines()) if a != b))
