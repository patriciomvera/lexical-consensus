"""Macros (\\Vf...) for manuscript v2f (A. review of v2e). No new computation: reads the post hoc outputs produced for v2c.
Writes manuscrito_v2f/generated/numbers_v2f.tex."""
import os
from pathlib import Path
import pandas as pd
BASE = Path(__file__).resolve().parents[1]; MS = BASE / os.environ.get("MS_DIR", "manuscrito_v2f"); PH = BASE / "posthoc_v2c"
ALL = ["R0_dinov2s","O1_dinov2b","R1_cvcl","E1_siglip","O2_openclip","E2_vitsup","E3_rn50sup","E4_mae","F1_rn50rand0","F2_pixels"]
v = {e: float(pd.read_csv(PH / f"out/p03_{e}.csv").set_index("model").loc["sup_dmean", "LR_cond_given_z"]) for e in ALL}
e_min = min(v, key=v.get); print("min LR condition | mean-exemplar distance:", e_min, round(v[e_min], 1))
assert e_min == "E3_rn50sup" and f"{v[e_min]:,.0f}" == "14,755"
(MS / "generated/numbers_v2f.tex").write_text("% AUTO-GENERATED by scripts/make_numbers_v2f.py -- do not edit\n"
    + "\\newcommand{\\VfSupDmeanCondChiMinAll}{" + f"{v[e_min]:,.0f}".replace(",", "{,}") + "}\n")
print("1 macro, 1 check, 0 failures")
