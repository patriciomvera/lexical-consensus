# EXPLORATORIO POST HOC (DESV §34; paperreview.ai Q4). Fuera del plan congelado y de la familia Holm.
suppressMessages(library(lme4)); set.seed(42)
d <- read.csv("data/h4_long.csv"); d$person <- factor(d$subid)
d$condition <- factor(c(one="one",three_subordinate="sub","3sub"="sub",three_basic="bas","3bas"="bas",three_superordinate="sup","3sup"="sup")[d$condition], levels=c("one","sub","bas","sup"))
k <- read.csv("data/xtmem/experiment_key.csv")[1:12,]; k$exp <- as.integer(k$exp); k$order <- gsub('"','',k$order)
d$order <- factor(k$order[match(d$exp, k$exp)], levels=c("1-3","3-1"))
print(table(k$exp, k$order)); stopifnot(!any(is.na(d$order)))
d$zd <- as.numeric(scale(d$dist)); d$level <- factor(d$level, levels=c("bas","sub","sup")); d$image <- factor(d$image)
cat(sprintf("N obs=%d personas=%d obs_1-3=%d obs_3-1=%d\n", nrow(d), nlevels(d$person), sum(d$order=="1-3"), sum(d$order=="3-1")))
ctl <- glmerControl(optimizer="bobyqa", optCtrl=list(maxfun=2e5))
w <- function(m) paste(m@optinfo$conv$lme4$messages, collapse=";")
re <- "+ (1 + zd | person) + (1 | image)"
mb0 <- glmer(as.formula(paste("selected ~ zd*condition + condition*order + level", re)), d, binomial, control=ctl)
cat("Mbase warn:", w(mb0), "singular:", isSingular(mb0), "\n"); flush.console()
mb  <- update(mb0, . ~ . + zd:order)
cat("Mb warn:", w(mb), "singular:", isSingular(mb), "\n"); print(round(summary(mb)$coefficients, 4)); flush.console()
print(anova(mb0, mb))
mc  <- update(mb, . ~ . + zd:condition:order)
cat("Mc warn:", w(mc), "singular:", isSingular(mc), "\n"); print(round(summary(mc)$coefficients, 4))
print(anova(mb, mc))
lb <- as.numeric(2*(logLik(mb)-logLik(mb0))); pb <- pchisq(lb, 1, lower.tail=FALSE)
lc <- as.numeric(2*(logLik(mc)-logLik(mb))); pc <- pchisq(lc, 3, lower.tail=FALSE)
ph <- p.adjust(c(pb, pc), "holm")
cat(sprintf("LR_zd_order chi2(1)=%.3f p=%.4g p_holm2=%.4g\n", lb, pb, ph[1]))
cat(sprintf("LR_zd_cond_order chi2(3)=%.3f p=%.4g p_holm2=%.4g\n", lc, pc, ph[2]))
co <- summary(mb)$coefficients["zd:order3-1",]; ci <- co[1]+c(-1,1)*qnorm(.975)*co[2]
cat(sprintf("MB zd:order3-1=%.4f SE=%.4f CI[%.4f, %.4f] z=%.3f p=%.4g\n", co[1], co[2], ci[1], ci[2], co[3], co[4]))
cz <- summary(mb)$coefficients["zd",]; cat(sprintf("MB zd(ref one, 1-3)=%.4f SE=%.4f\n", cz[1], cz[2]))
